/** The Date header and Kestrel's reason phrases. */

const DAYS = ['Thu', 'Fri', 'Sat', 'Sun', 'Mon', 'Tue', 'Wed'] as const;
const MONTHS = [
  'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
] as const;

/** RFC 9110 IMF-fixdate, as net/http's TimeFormat and Kestrel write it. */
export function httpDate(time: Date | number): string {
  const ms = typeof time === 'number' ? time : time.getTime();
  const seconds = Math.floor(ms / 1000);
  const days = Math.floor(seconds / 86_400);
  const rest = seconds % 86_400;
  const [year, month, day] = civilFromDays(days);
  return `${DAYS[days % 7]}, ${String(day).padStart(2, '0')} ${MONTHS[month - 1]} ${year} ${String(Math.floor(rest / 3600)).padStart(2, '0')}:${String(Math.floor(rest / 60) % 60).padStart(2, '0')}:${String(rest % 60).padStart(2, '0')} GMT`;
}

function civilFromDays(days: number): [number, number, number] {
  const z = days + 719_468;
  const era = Math.floor(z / 146_097);
  const doe = z % 146_097;
  const yoe = Math.floor((doe - Math.floor(doe / 1460) + Math.floor(doe / 36_524) - Math.floor(doe / 146_096)) / 365);
  const doy = doe - (365 * yoe + Math.floor(yoe / 4) - Math.floor(yoe / 100));
  const mp = Math.floor((5 * doy + 2) / 153);
  const day = doy - Math.floor((153 * mp + 2) / 5) + 1;
  const month = mp < 10 ? mp + 3 : mp - 9;
  const year = yoe + era * 400 + (month <= 2 ? 1 : 0);
  return [year, month, day];
}

